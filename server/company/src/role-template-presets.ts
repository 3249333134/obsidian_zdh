function note(role:string,title:string,body:string):NotePreset {
 return {title,body:`---
type: knowledge
role: "${role}"
status: draft
owner: ""
project: ""
source: ""
updated: ""
sensitivity: "待确认"
tags:
  - "${role}"
---

# ${title}

> 这是待填写的个人草稿。空白不代表事实；不适用的部分请删除。填写后核对依据，再预览提交共享。

${body.trim()}

## 来源与维护

- 关联笔记／资料链接：
- 原始资料日期与适用范围：
- 本次核实时间：
- 维护人／复核人：
- 修订记录与失效条件：

## 下一步行动

| 行动 | 负责人 | 验收结果 | 截止时间 | 状态 |
| --- | --- | --- | --- | --- |
|  |  |  | 未确定 | 待确认 |

> 行动需另行确认创建为计划；本模板不会自动指派、排期或发布。
`};
}
function preset(key:string,name:string,categories:string[],rules:string,questions:string[],plans:string[],notes:NotePreset[]):RolePreset {
 return {key,role:{name,categories,rules,noteTemplate:notes[0].body,questions,plans,entries:['知识','计划','复盘']},notes};
}

